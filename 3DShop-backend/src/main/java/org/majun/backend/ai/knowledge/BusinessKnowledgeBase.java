package org.majun.backend.ai.knowledge;

import org.majun.backend.ai.model.IntentType;
import org.springframework.stereotype.Service;

/**
 * 业务知识库
 * 为 AI 提供业务相关的背景知识
 */
@Service
public class BusinessKnowledgeBase {

    /**
     * 获取业务上下文信息
     *
     * @param intent 意图类型
     * @return 业务知识文本
     */
    public String getContext(IntentType intent) {
        return switch (intent) {
            case PRINT_PRICE -> getPrintPriceContext();
            case MATERIAL -> getMaterialContext();
            case DELIVERY -> getDeliveryContext();
            case ORDER_STATUS -> getOrderStatusContext();
            case TECHNICAL -> getTechnicalContext();
            case COMPLAINT -> getComplaintContext();
            default -> "";
        };
    }

    /**
     * 打印价格相关知识
     */
    private String getPrintPriceContext() {
        return """
                ## 3D打印价格说明

                ### 计价方式
                打印价格 = 材料重量(克) × 材料单价(元/克)

                ### 影响价格的因素
                1. **材料类型**：不同材料价格不同
                   - PLA：约0.05-0.1元/克
                   - ABS：约0.08-0.15元/克
                   - 光敏树脂：约0.3-0.5元/克
                   - 尼龙：约0.2-0.4元/克
                2. **模型体积**：越大越贵
                3. **填充密度**：填充越高，材料越多
                4. **精度要求**：高精度需要更长时间

                ### 价格区间参考
                - 小型模型(50g以下): 约10-50元
                - 中型模型(50-200g): 约50-200元
                - 大型模型(200g以上): 200元以上

                **重要提示**：用户需要上传模型文件才能获取准确报价。
                """;
    }

    /**
     * 材料相关知识
     */
    private String getMaterialContext() {
        return """
                ## 可选材料介绍

                ### 常用材料
                1. **PLA（聚乳酸）**
                   - 特点：环保、易打印、颜色丰富
                   - 适用：大件模型、展示模型、初学者作品
                   - 价格：约0.05-0.1元/克
                   - 缺点：不耐高温、强度一般

                2. **ABS（丙烯腈-丁二烯-苯乙烯）**
                   - 特点：耐高温、韧性好
                   - 适用：功能性零件、机械外壳
                   - 价格：约0.08-0.15元/克
                   - 缺点：打印时有气味、需要加热床

                3. **光敏树脂**
                   - 特点：精度高、表面光滑
                   - 适用：精细模型、手办、首饰
                   - 价格：约0.3-0.5元/克
                   - 缺点：易碎、怕阳光直射

                4. **尼龙（PA）**
                   - 特点：强度高、耐磨、韧性好
                   - 适用：齿轮、轴承、工具零件
                   - 价格：约0.2-0.4元/克
                   - 缺点：吸湿性强

                ### 材料选择建议
                - 精细模型/手办/首饰 → 光敏树脂
                - 大件展示模型 → PLA
                - 功能性零件 → ABS 或 尼龙
                - 齿轮/耐磨件 → 尼龙
                """;
    }

    /**
     * 配送相关知识
     */
    private String getDeliveryContext() {
        return """
                ## 配送时间说明

                ### 打印周期
                - 普通订单: 3-5个工作日
                - 加急订单: 1-2个工作日（加收30%费用）
                - 大型/复杂订单: 5-7个工作日

                ### 物流时间
                - 同城配送: 1-2天
                - 省内快递: 2-3天
                - 跨省快递: 3-5天

                ### 配送方式
                1. 快递配送（顺丰/圆通）
                2. 同城配送
                3. 到店自取

                ### 物流查询
                用户可以在"我的订单"中查看物流状态和快递单号。
                """;
    }

    /**
     * 订单状态相关知识
     */
    private String getOrderStatusContext() {
        return """
                ## 订单状态说明

                ### 订单状态含义
                - **待付款(0)**: 订单已创建，等待支付
                - **生产中(1)**: 支付成功，正在3D打印
                - **待发货(2)**: 打印完成，等待发货
                - **已完成(3)**: 订单已完成
                - **已取消(4)**: 订单已取消

                ### 查询方式
                用户可以通过以下方式查询订单:
                1. 在"我的订单"页面查看所有订单
                2. 提供订单号进行查询
                3. 联系客服查询

                ### 常见问题处理
                - 订单超时未付款：30分钟后自动取消
                - 想要修改订单：需联系客服处理
                - 退款申请：在订单详情页申请售后
                """;
    }

    /**
     * 技术问题相关知识
     */
    private String getTechnicalContext() {
        return """
                ## 3D打印技术知识

                ### 支持的文件格式
                - STL（最常用）
                - OBJ
                - 3MF
                - STEP/STP

                ### 打印参数说明
                - **层高**：影响精度和打印时间
                  - 0.1mm：高精度，打印慢
                  - 0.2mm：标准精度
                  - 0.3mm：快速打印，精度较低

                - **填充密度**：影响强度和材料用量
                  - 10-20%：轻量级模型
                  - 30-50%：标准强度
                  - 80-100%：高强度需求

                ### 模型要求
                - 最小壁厚：建议≥1mm
                - 最小细节：建议≥0.5mm
                - 模型尺寸限制：根据具体打印机

                ### 常见打印问题
                1. 层纹明显：层高设置问题
                2. 翘边：温度或平台调平问题
                3. 拉丝：回抽设置问题
                """;
    }

    /**
     * 投诉处理相关知识
     */
    private String getComplaintContext() {
        return """
                ## 投诉处理流程

                ### 售后服务承诺
                - 打印质量问题：免费重打或退款
                - 物流损坏：协助理赔或重发
                - 发货延迟：可申请退款

                ### 处理流程
                1. 用户提交售后申请
                2. 客服审核问题
                3. 提供解决方案（重打/退款/补偿）
                4. 完成处理

                ### 投诉升级
                如用户对处理结果不满意，可以:
                - 申请平台介入
                - 联系更高一级客服
                """;
    }
}
